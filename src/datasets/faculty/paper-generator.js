/* Every paper in the library owns its own questionList — the preview
   renders the SELECTED paper's questions, never a shared template.
   Competitive seeds pull 25 questions each from the competitive
   question foundation (stable CQ ids, exam+subject matched).
   University seeds carry their own deterministic pools (same pattern
   as the original embedded competitive lists). `questions` and
   `totalMarks` are COMPUTED from the list so the card metadata can
   never drift from the actual content. */

const sumMarks = (list) => list.reduce((s, q) => s + (q.marks ?? 0), 0)

const stampList = (rows, prefix) => rows.map((q, i) => ({
  id: `${prefix}-${String(i + 1).padStart(2, '0')}`,
  no: i + 1,
  text: q.question,
  type: q.type,
  difficulty: q.difficulty,
  marks: q.marks,
  bloom: q.bloom,
  chapter: q.chapter,
  topic: q.topic,
  options: q.options,
  answer: q.answer,
  isPyq: !!q.isPyq,
  pyqYear: q.pyqYear ?? null,
  explanation: q.explanation ?? null,
}))

const U = (chapter, topic, type, difficulty, marks, bloom, question, options, answer) => ({
  chapter, topic, type, difficulty, marks, bloom, question, options, answer,
})

